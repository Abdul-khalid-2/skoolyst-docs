      <h1>Skoolyst Overview</h1>
      <p class="lead">Skoolyst is an educational technology ecosystem designed to connect schools, teachers, students, parents and educational services through digital platforms.</p>

      <h2 id="what-is-skoolyst">What is Skoolyst?</h2>
      <p>Skoolyst is not a single product but an ecosystem — a family of interconnected educational technology applications built around a shared purpose. The goal is to bring educational resources, tools and services together in one connected environment so that schools, teachers, students and parents can discover, share and benefit from them more easily.</p>
      <p>At its core, Skoolyst is about reducing the fragmentation that exists in education today, where schools, learning materials, assessment tools and educational media are often scattered across disconnected platforms.</p>

      <h2 id="vision">Vision</h2>
      <p>To create a unified digital ecosystem where educational resources, tools and communities are accessible, organized and interconnected — making learning more efficient and effective for everyone involved.</p>

      <h2 id="mission">Mission</h2>
      <p>To build a suite of educational technology products that simplify how schools, teachers, students and parents discover, access and use educational resources — starting with a unified platform and evolving toward specialized applications that serve specific needs.</p>

      <h2 id="who-skoolyst-is-for">Who Skoolyst is For</h2>
      <ul>
        <li><strong>Schools</strong> — to list, organize and manage their presence and resources</li>
        <li><strong>Teachers</strong> — to access educational materials, create assessments and share content</li>
        <li><strong>Students</strong> — to discover learning resources, practice with MCQs and access educational media</li>
        <li><strong>Parents</strong> — to find schools and educational resources for their children</li>
        <li><strong>Educational service providers</strong> — to reach their audience through listings and advertising</li>
      </ul>

      <h2 id="problems-skoolyst-solves">Main Problems Skoolyst Solves</h2>
      <ul>
        <li><strong>Fragmentation</strong> — Educational resources are scattered across many disconnected platforms. Skoolyst brings them together.</li>
        <li><strong>Discovery</strong> — Finding schools, materials and educational content is difficult. Skoolyst provides organized listings and directories.</li>
        <li><strong>Access</strong> — Quality educational tools are often behind paywalls or hard to use. Skoolyst aims to make them more accessible.</li>
        <li><strong>Organization</strong> — Educational content lacks structure. Skoolyst provides categorized, searchable access to resources.</li>
      </ul>

      <h2 id="how-the-ecosystem-works">How the Ecosystem Works</h2>
      <p>The Skoolyst ecosystem is designed to grow modularly. It starts with a single unified application containing multiple modules, and evolves toward independent specialized applications connected by a shared ecosystem.</p>
      <p>Currently, the main Skoolyst application contains four modules:</p>
      <ul>
        <li><strong>Schools Listing</strong> — a directory of educational institutions</li>
        <li><strong>Stores</strong> — a marketplace for educational products and materials</li>
        <li><strong>Media</strong> — educational media content including videos and audio</li>
        <li><strong>MCQs</strong> — multiple-choice question practice and assessment tools</li>
      </ul>
      <p>As the ecosystem grows, these modules are planned to become independent applications under their own subdomains, each focused on its specific domain while remaining connected to the broader Skoolyst ecosystem.</p>

      <h2 id="current-development-status">Current Development Status</h2>
      <p>Skoolyst is currently in early development. The main application is being actively built with its core modules. No production versions have been released yet. Version history reflects development-stage builds only.</p>
      <p>For the latest status, see <a href="versions.php">Versions</a> and <a href="release-notes.php">Release Notes</a>.</p>

      <h2 id="future-direction">Future Direction</h2>
      <p>The long-term plan for Skoolyst includes:</p>
      <ul>
        <li>Separating core modules into independent applications under dedicated subdomains</li>
        <li>Adding new products such as Ads and Blogs</li>
        <li>Building developer APIs to enable third-party integration</li>
        <li>Expanding the ecosystem with additional educational tools and services</li>
      </ul>
      <p>These plans are subject to change as development progresses. No specific timelines or launch dates are announced.</p>

